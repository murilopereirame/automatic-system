/**
 * The output folder of a run: a place outside the git worktree where Claude,
 * workflow commands and the web shell put files meant to leave the container
 * (screenshots, reports, build artifacts, exported data).
 *
 * Every run gets `<outputsDir>/<run id>`. The folder lives on its own volume,
 * apart from the run workspaces, so cleaning up workspaces never removes it.
 * Sandbox processes find it in the `AUTOWORKER_OUTPUT_DIR` variable.
 *
 * Files are listed and read back as the agent user, never as the server's own
 * user. A symbolic link placed in the folder therefore cannot make the server
 * hand out a file the agent could not read itself, such as the database.
 */
import { spawn } from 'node:child_process';
import path from 'node:path';
import type { Readable } from 'node:stream';
import { config } from '../config.js';
import type { OutputFile, OutputListing } from '../types.js';
import { agentExec, agentIdentity, agentMkdir, baseEnv } from './agent.js';

/** Name of the variable that tells sandbox processes where the run's output folder is. */
export const OUTPUT_DIR_VARIABLE = 'AUTOWORKER_OUTPUT_DIR';

/** Listing stops after this many files, so a runaway command cannot make the page unusable. */
const MAX_LISTED_FILES = 1000;

/** `<outputsDir>/<run id>`. Run ids are generated by the server, but are checked anyway because they arrive in URLs. */
export function runOutputDir(runId: string): string {
  if (!/^[A-Za-z0-9-]+$/.test(runId)) throw new Error(`Invalid run id "${runId}"`);
  return path.join(config.outputsDir, runId);
}

/** The variable every sandbox process of the run gets. */
export function outputEnv(runId: string): Record<string, string> {
  return { [OUTPUT_DIR_VARIABLE]: runOutputDir(runId) };
}

/** Creates the run's output folder, owned by the agent user. Called before the first step runs. */
export async function prepareOutputDir(runId: string): Promise<void> {
  await agentMkdir(runOutputDir(runId));
}

/**
 * Regular files in the run's output folder, newest first. `find` does not
 * follow symbolic links, so links and whatever they point to are left out.
 */
export async function listOutputs(runId: string): Promise<OutputListing> {
  const dir = runOutputDir(runId);
  const found = await agentExec('find', [dir, '-type', 'f', '-printf', '%s\\t%T@\\t%P\\0'], { cwd: '/' });
  // No folder yet (the run has not started, or it is older than this feature): nothing to list.
  if (found.code !== 0 && found.stdout === '') return { dir, files: [], truncated: false };

  const files = found.stdout
    // Entries end with a NUL byte and the path comes last, so names with tabs or line breaks are read correctly.
    .split('\0')
    .filter(Boolean)
    .map((entry): OutputFile => {
      const [size, modified, ...name] = entry.split('\t');
      return { path: name.join('\t'), size: Number(size), modifiedAt: new Date(Number(modified) * 1000).toISOString() };
    })
    .sort((a, b) => b.modifiedAt.localeCompare(a.modifiedAt) || a.path.localeCompare(b.path));
  return { dir, files: files.slice(0, MAX_LISTED_FILES), truncated: files.length > MAX_LISTED_FILES };
}

/**
 * Starts reading one file of the output folder. Only paths that the listing
 * shows are accepted, which rules out `..`, absolute paths and links.
 * Returns undefined when there is no such file.
 */
export async function readOutput(runId: string, relative: string): Promise<{ file: OutputFile; stream: Readable } | undefined> {
  const { dir, files } = await listOutputs(runId);
  const file = files.find((candidate) => candidate.path === relative);
  if (!file) return undefined;
  return { file, stream: agentStream('cat', ['--', path.join(dir, file.path)]) };
}

/** The whole output folder as a gzipped tar archive, read as the agent user. Links are stored as links, not followed. */
export function archiveOutputs(runId: string): Readable {
  return agentStream('tar', ['-czf', '-', '-C', runOutputDir(runId), '.']);
}

/** Runs a command as the agent user and returns its standard output as a stream. */
function agentStream(command: string, args: string[]): Readable {
  const child = spawn(command, args, { cwd: '/', env: baseEnv(), ...agentIdentity(), stdio: ['ignore', 'pipe', 'ignore'] });
  child.on('error', (error) => child.stdout.destroy(error));
  return child.stdout;
}
